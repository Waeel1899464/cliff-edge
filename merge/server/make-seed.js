// Writes server/seed.sql from the hand-written recipes in index.html (levels 1-3),
// so the server knows the starting things and never asks the AI about them.
// Run: node server/make-seed.js
const fs = require('fs');
const path = require('path');
const html = fs.readFileSync(path.join(__dirname, '..', 'index.html'), 'utf8');
const grab = (start, end) => html.slice(html.indexOf(start), html.indexOf(end, html.indexOf(start)));
const baseSrc = grab('const BASE = ', '];') + '];';
const bookSrc = grab('const BOOK_RAW = ', '\n  };') + '\n  };';
const { BASE: base, BOOK_RAW } = Function(baseSrc + bookSrc + 'return { BASE, BOOK_RAW };')();
const norm = s => String(s).trim().toLowerCase().replace(/\s+/g, ' ');
const key = (t, a, b) => { const x = [norm(a), norm(b)].sort(); return t + '|' + x[0] + '+' + x[1]; };
const q = s => "'" + String(s).replace(/'/g, "''") + "'";
const items = [], combos = [];
for (const b of base) items.push(`(1, ${q(norm(b.n))}, ${q(b.n)}, ${q(b.e)})`);
for (const t of [2, 3]) for (const [a, b, n, e] of BOOK_RAW[t]) {
  items.push(`(${t}, ${q(norm(n))}, ${q(n)}, ${q(e)})`);
  combos.push(`(${q(key(t, a, b))}, ${t}, ${q(n)}, ${q(e)}, true)`);
}
const sql = `-- Generated by make-seed.js from index.html. Starting things (levels 1-3).
insert into public.merge_items (tier, key, name, emoji) values
${items.join(',\n')}
on conflict do nothing;

insert into public.merge_combos (key, tier, name, emoji, seeded) values
${combos.join(',\n')}
on conflict do nothing;
`;
fs.writeFileSync(path.join(__dirname, 'seed.sql'), sql);
console.log('items', items.length, 'combos', combos.length);
